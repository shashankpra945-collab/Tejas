export const SUPPORTED_EMERGENCY_CITIES: string[] = Object.keys(CITY_EMERGENCY_FACILITIES);

/**
 * Returns emergency facilities based on city name, with safe default fallback
 */
export function getEmergencyFacilitiesForCity(city: string): {
  hospitals: HospitalEmergencyFacility[];
  doctors: DoctorEmergencyListing[];
} {
  const normalizedCity = Object.keys(CITY_EMERGENCY_FACILITIES).find(
    (c) => c.toLowerCase() === (city || '').toLowerCase()
  );

  if (normalizedCity) {
    return CITY_EMERGENCY_FACILITIES[normalizedCity];
  }

  // Fallback to Surat
  return CITY_EMERGENCY_FACILITIES['Surat'];
}
