// Helper to expand raw state config into full GisEnvironment instances
function expandStateData(raw: RawStateConfig): StateInfo {
  const cities: GisEnvironment[] = raw.cityList.map((c) => {
    const tempC = c.tempOffset ? raw.baseTemp + c.tempOffset : raw.baseTemp;
    const aqi = c.aqiOffset ? Math.max(15, raw.baseAqi + c.aqiOffset) : raw.baseAqi;
    let aqiCategory: GisEnvironment['aqiCategory'] = 'Moderate';
    if (aqi <= 50) aqiCategory = 'Good';
    else if (aqi <= 100) aqiCategory = 'Good';
    else if (aqi <= 200) aqiCategory = 'Moderate';
    else if (aqi <= 300) aqiCategory = 'Poor';
    else if (aqi <= 400) aqiCategory = 'Very Poor';
    else aqiCategory = 'Severe';

    const activeOutbreaks: OutbreakAlertItem[] = c.customOutbreak
      ? [c.customOutbreak]
      : [raw.primaryOutbreak];

    return {
      city: c.name,
      state: raw.name,
      lat: c.lat ?? raw.baseLat,
      lng: c.lng ?? raw.baseLng,
      tempC,
      humidityPercent: raw.baseHumidity,
      aqi,
      aqiCategory,
      season: raw.season,
      activeOutbreaks,
    };
  });

  return {
    name: raw.name,
    type: raw.type,
    zone: raw.zone,
    cities,
  };
}

export const INDIAN_STATES_DATA: StateInfo[] = RAW_INDIAN_STATES.map(expandStateData);

// Helper: Flattened list of all cities across India (500+ major cities and districts)
export const ALL_INDIA_GIS_CITIES: GisEnvironment[] = INDIAN_STATES_DATA.flatMap(
  (state) => state.cities
);

// Helper: Find state by city name
export function findStateByCity(cityName: string): StateInfo | undefined {
  return INDIAN_STATES_DATA.find((s) => s.cities.some((c) => c.city.toLowerCase() === cityName.toLowerCase()));
}

// Helper: Get all cities for a specific state name
export function getCitiesForState(stateName: string): GisEnvironment[] {
  const state = INDIAN_STATES_DATA.find(
    (s) => s.name.toLowerCase() === stateName.toLowerCase()
  );
  return state ? state.cities : [];
}

// Helper: Get GisEnvironment object by State and City name
export function getGisByStateAndCity(stateName: string, cityName: string): GisEnvironment | undefined {
  const state = INDIAN_STATES_DATA.find(
    (s) => s.name.toLowerCase() === stateName.toLowerCase()
  );
  if (!state) return undefined;
  return state.cities.find((c) => c.city.toLowerCase() === cityName.toLowerCase());
}
